"""
SQLAlchemy ORM Data Models
--------------------------
Schema definitions for:
  1. StockPrice: Historical daily OHLCV bars across 26 equities.
  2. ASPIIndex: Official daily ASPI market benchmark index point-in-time closes.
  3. ForecastPrediction: 30-day ahead multi-quantile cones, SHAP drivers, and heuristic cards.
  4. PipelineRun: Automated daily pipeline execution logs, metrics, and audit history.
"""

from __future__ import annotations

import datetime
from sqlalchemy import (
    BigInteger,
    Column,
    Date,
    DateTime,
    Float,
    Integer,
    Numeric,
    PrimaryKeyConstraint,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.types import JSON

from src.database.session import Base


class StockPrice(Base):
    """
    Daily OHLCV equities table acting as the continuous source of truth.
    Primary key: composite (symbol, date).
    """
    __tablename__ = "stock_prices"

    symbol = Column(String(32), primary_key=True, index=True, nullable=False)
    date = Column(Date, primary_key=True, index=True, nullable=False)
    open = Column(Numeric(12, 2), nullable=False)
    high = Column(Numeric(12, 2), nullable=False)
    low = Column(Numeric(12, 2), nullable=False)
    close = Column(Numeric(12, 2), nullable=False)
    volume = Column(BigInteger, nullable=False, default=0)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = (
        PrimaryKeyConstraint("symbol", "date"),
        UniqueConstraint("symbol", "date", name="uq_stock_price_symbol_date"),
    )

    def __repr__(self) -> str:
        return f"<StockPrice({self.symbol}, {self.date}, Close={self.close})>"


class ASPIIndex(Base):
    """
    Official All Share Price Index (ASPI) point-in-time historical closes.
    Primary key: date.
    """
    __tablename__ = "aspi_index"

    date = Column(Date, primary_key=True, index=True, nullable=False)
    close = Column(Numeric(12, 2), nullable=False)
    high = Column(Numeric(12, 2), nullable=True)
    low = Column(Numeric(12, 2), nullable=True)
    change = Column(Numeric(12, 2), nullable=True)
    percentage = Column(Numeric(6, 2), nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    def __repr__(self) -> str:
        return f"<ASPIIndex({self.date}, Close={self.close})>"


class ForecastPrediction(Base):
    """
    Historical 30-day forward forecasts generated by Multi-Quantile LightGBM models.
    Unique constraint: (symbol, as_of_date).
    """
    __tablename__ = "forecast_predictions"

    id = Column(Integer, primary_key=True, autoincrement=True)
    symbol = Column(String(32), nullable=False, index=True)
    as_of_date = Column(Date, nullable=False, index=True)
    current_price = Column(Numeric(12, 2), nullable=False)
    price_p10 = Column(Numeric(12, 2), nullable=False)
    price_p50 = Column(Numeric(12, 2), nullable=False)
    price_p90 = Column(Numeric(12, 2), nullable=False)
    expected_pct_change = Column(Numeric(6, 2), nullable=False)

    # Rich JSON payloads
    target_returns = Column(JSON, nullable=False)
    cone_trajectory = Column(JSON, nullable=False)
    shap_drivers = Column(JSON, nullable=False)
    heuristic_signals = Column(JSON, nullable=False)

    created_at = Column(DateTime(timezone=True), server_default=func.now())

    __table_args__ = (
        UniqueConstraint("symbol", "as_of_date", name="unique_symbol_date_forecast"),
    )

    def __repr__(self) -> str:
        return f"<ForecastPrediction({self.symbol}, {self.as_of_date}, P50={self.price_p50})>"


class PipelineRun(Base):
    """
    Audit log of automated daily pipeline runs, execution durations, records ingested, and errors.
    """
    __tablename__ = "pipeline_runs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    run_date = Column(Date, nullable=False, index=True)
    job_name = Column(String(64), nullable=False)
    status = Column(String(20), nullable=False)  # 'SUCCESS', 'FAILED', 'WARNING'
    records_ingested = Column(Integer, default=0)
    models_retrained = Column(Integer, default=0)
    duration_seconds = Column(Numeric(8, 2), default=0.0)
    message = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    def __repr__(self) -> str:
        return f"<PipelineRun({self.job_name}, {self.run_date}, Status={self.status})>"
